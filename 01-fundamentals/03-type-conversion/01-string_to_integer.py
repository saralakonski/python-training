# Solicita um número, converte para inteiro, calcula o dobro e exibe o resultado.
# Requests a number, converts it to an integer, calculates its double, and displays the result.

number = input("Digite um número: ")
int_number = int(number)
double_number = int_number * 2

print(f"Seu número é: {number}. O dobro do seu número é {double_number}")