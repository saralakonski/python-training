# Solicita ao usuário que digite dois números inteiros e realiza a subtração entre eles
# Requests the user to input two integer numbers and performs the subtraction between them

first_number = int(input("Digite o primeiro número: "))
second_number = int(input("Digite o segundo número: "))

print(f"O resultado da subtração entre {first_number} e {second_number} é {first_number - second_number}.")