# Solicita ao usuário que digite dois números inteiros e exibe a multiplicação deles
# Requests the user to input two integer numbers and displays their multiplication
first_number = int(input("Digite o primeiro número: "))
second_number = int(input("Digite o segundo número: "))

print(f"O resultado da multiplicação entre {first_number} e {second_number} é {first_number * second_number}.")